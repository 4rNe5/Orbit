/** Fills {name} slots of a translated string with nodes. */
function rich(s: string, nodes: Record<string, ReactNode>): ReactNode {
  return s.split(/(\{\w+\})/).map((part, i) => {
    const k = /^\{(\w+)\}$/.exec(part)?.[1];
    return k && k in nodes ? <Fragment key={i}>{nodes[k]}</Fragment> : part;
  });
}

/** Song metadata from the Rotaeno wiki (src/data/songinfo.json, generated by scripts/sync-wiki.mjs). */
export interface SongInfo {
  w: string; // wiki page title
  a: string; // artist
  d: number; // duration (s)
  v: string; // release version
  jd: string; // jacket designer
  s?: string; // source
  t?: [lang: string, title: string][];
  c: Record<string, { cd: string; n?: [total: number, tap: number, flick: number, slide: number, katch: number, rotate: number] }>;
}

let infoCache: Record<string, SongInfo> | null = null;
let infoPromise: Promise<Record<string, SongInfo>> | null = null;
export function loadSongInfo() {
  if (infoCache) return Promise.resolve(infoCache);
  infoPromise ??= import("@/data/songinfo.json").then((m) => (infoCache = m.default as unknown as Record<string, SongInfo>));
  return infoPromise;
}

// ── URL-synced open state (?song=<id>) ──────────────────────────────────────
const SONG_EVENT = "orbit:song";
const subscribe = (cb: () => void) => {
  window.addEventListener("popstate", cb);
  window.addEventListener(SONG_EVENT, cb);
  return () => {
    window.removeEventListener("popstate", cb);
    window.removeEventListener(SONG_EVENT, cb);
  };
};
const readSong = () => new URLSearchParams(window.location.search).get("song");
function writeSong(id: string | null, mode: "push" | "replace") {
  const url = new URL(window.location.href);
  if (id) url.searchParams.set("song", id);
  else url.searchParams.delete("song");
  if (mode === "push") window.history.pushState(null, "", url);
  else window.history.replaceState(null, "", url);
  window.dispatchEvent(new Event(SONG_EVENT));
}

const Ctx = createContext<(songId: string) => void>(() => {});

/** Opens the song info sheet. Safe to call outside the provider (no-op). */
export function useSongDialog() {
  return useContext(Ctx);
}

export function SongDialogProvider({ children }: { children: React.ReactNode }) {
  const songId = useSyncExternalStore(subscribe, readSong, () => null);
  const pushed = useRef(false);
  const open = useCallback((id: string) => {
    if (readSong() === id) return;
    writeSong(id, readSong() ? "replace" : "push");
    pushed.current = true;
  }, []);
  const close = useCallback(() => {
    if (pushed.current) {
      pushed.current = false;
      window.history.back();
    } else writeSong(null, "replace");
  }, []);
  /** Leave the dialog without a history step (before navigating elsewhere). */
  const dismiss = useCallback(() => {
    pushed.current = false;
    writeSong(null, "replace");
  }, []);
  return (
    <Ctx.Provider value={open}>
      {children}
      {songId && <SongDialog songId={songId} onClose={close} onDismiss={dismiss} />}
    </Ctx.Provider>
  );
}

/** Wraps content in a button that opens the song sheet. */
export function SongButton({ songId, className, children, label }: { songId: string; className?: string; children: React.ReactNode; label?: string }) {
  const open = useSongDialog();
  const t = useT(T);
  return (
    <button type="button" onClick={() => open(songId)} className={cx("block cursor-pointer text-left", className)} aria-label={label ? t("infoOf", { label }) : t("info")}>
      {children}
    </button>
  );
}

function SongDialog({ songId, onClose, onDismiss }: { songId: string; onClose: () => void; onDismiss: () => void }) {
  const closeRef = useRef<HTMLButtonElement>(null);
  const router = useRouter();
  const t = useT(T);

  useEffect(() => {
    const prev = document.activeElement as HTMLElement | null;
    closeRef.current?.focus();
    const onKey = (e: KeyboardEvent) => e.key === "Escape" && onClose();
    window.addEventListener("keydown", onKey);
    const overflow = document.body.style.overflow;
    document.body.style.overflow = "hidden";
    return () => {
      window.removeEventListener("keydown", onKey);
      document.body.style.overflow = overflow;
      prev?.focus?.();
    };
  }, [onClose]);

  return (
    <div className="fixed inset-0 z-[60] flex items-end justify-center sm:items-center sm:p-6" role="dialog" aria-modal="true" aria-labelledby="song-title">
      <div className="absolute inset-0 bg-black/65 backdrop-blur-[2px]" onClick={onClose} aria-hidden />
      <div className="pop relative flex max-h-[90dvh] w-full max-w-[640px] flex-col overflow-hidden rounded-t-[22px] border border-line bg-paper shadow-2xl sm:rounded-[22px]">
        <button
          ref={closeRef}
          type="button"
          onClick={onClose}
          className="absolute right-3 top-3 z-10 grid h-9 w-9 place-items-center rounded-full bg-black/45 text-white hover:bg-black/60"
          aria-label={t("close")}
        >
          <svg width="16" height="16" viewBox="0 0 16 16" aria-hidden>
            <path d="M3.5 3.5l9 9M12.5 3.5l-9 9" stroke="currentColor" strokeWidth="1.8" strokeLinecap="round" />
          </svg>
        </button>
        <SongDetail
          songId={songId}
          variant="dialog"
          onOpenPage={() => {
            onDismiss();
            router.push(`/song/${encodeURIComponent(songId)}`);
          }}
        />
      </div>
    </div>
  );
}

const LANG: Record<string, keyof typeof T.ko> = { ko: "langKo", en: "langEn", ja: "langJa", "zh-Hant": "langZhHant", "zh-Hans": "langZhHans", "zh-CN": "langZhCN" };
const mmss = (s: number) => `${Math.floor(s / 60)}:${String(s % 60).padStart(2, "0")}`;
const day = (iso: string) => {
  const d = new Date(iso);
  return `${d.getFullYear() % 100}.${String(d.getMonth() + 1).padStart(2, "0")}.${String(d.getDate()).padStart(2, "0")}`;
};
const byDiff = (a: Chart, b: Chart) => DIFFICULTIES.indexOf(a.difficulty) - DIFFICULTIES.indexOf(b.difficulty);

/**
 * Song details: header, facts, charts with the player's record and history.
 * Used by the dialog and by /song/[id] (which passes server-side data so the page is static).
 */
export function SongDetail({
  songId,
  variant,
  initialInfo,
  fallbackCharts,
  onOpenPage,
}: {
  songId: string;
  variant: "dialog" | "page";
  initialInfo?: SongInfo | null;
  fallbackCharts?: Chart[];
  onOpenPage?: () => void;
}) {
  const { charts, scores, analysis, index, chartEvents, toast } = useApp();
  const t = useT(T);
  const locale = useLocale();
  const [loaded, setLoaded] = useState<{ id: string; info: SongInfo | null } | null>(null);
  const info = initialInfo !== undefined ? initialInfo : loaded?.id === songId ? loaded.info : infoCache ? (infoCache[songId] ?? null) : undefined;

  useEffect(() => {
    if (initialInfo !== undefined || infoCache) return;
    let alive = true;
    loadSongInfo().then(
      (all) => alive && setLoaded({ id: songId, info: all[songId] ?? null }),
      () => alive && setLoaded({ id: songId, info: null }),
    );
    return () => {
      alive = false;
    };
  }, [songId, initialInfo]);

  const list = useMemo(() => {
    const live = charts.filter((c) => c.songId === songId);
    return (live.length ? live : (fallbackCharts ?? [])).slice().sort(byDiff);
  }, [charts, songId, fallbackCharts]);
  const engine = useMemo(() => (index && analysis ? createTargetEngine(index, scores, analysis) : null), [index, scores, analysis]);

  const ids = list.map((c) => c.id).join(",");
  const [history, setHistory] = useState<{ key: string; events: ScoreEvent[] } | null>(null);
  useEffect(() => {
    if (!ids) return;
    let alive = true;
    chartEvents(ids.split(",")).then((ev) => alive && setHistory({ key: ids, events: ev }));
    return () => {
      alive = false;
    };
  }, [ids, chartEvents]);
  const events = history?.key === ids ? history.events : [];

  const main: Chart | undefined = list.find((c) => c.difficulty === "IV") ?? list[list.length - 1];
  if (!main) return null;
  const title = main.songTitle || main.title;
  const pack = main.songPack || main.pack;
  const category = packCategory(pack, locale);
  const wikiUrl = info ? `https://wiki.rotaeno.cn/${encodeURIComponent(info.w.replace(/ /g, "_"))}` : null;
  const page = variant === "page";

  const copyLink = async () => {
    const url = `${window.location.origin}/song/${encodeURIComponent(songId)}`;
    try {
      await navigator.clipboard.writeText(url);
      toast(t("copied"));
    } catch {
      toast(url);
    }
  };

  return (
    <>
      {/* header: jacket over its own blurred art */}
      <div className={cx("relative shrink-0 overflow-hidden", page && "rounded-[22px] border border-line")}>
        <div className="absolute inset-0 scale-125 opacity-60 blur-2xl" aria-hidden>
          <Jacket songId={songId} title={title} rounded="rounded-none" className="h-full w-full" eager />
        </div>
        <div className="absolute inset-0 bg-gradient-to-b from-black/30 via-paper/70 to-paper" aria-hidden />
        <div className={cx("relative flex gap-4 p-5 pt-6 sm:gap-5 sm:p-6", page && "sm:p-8")}>
          <Jacket songId={songId} title={title} rounded="rounded-[14px]" className={cx("shadow-xl ring-1 ring-white/15", page ? "w-32 sm:w-48" : "w-28 sm:w-36")} eager />
          <div className="min-w-0 flex-1 self-end">
            <div className="text-[12px] font-medium text-ink-2">
              {packName(pack, locale)}
              {category && <span className="text-mist"> · {category}</span>}
            </div>
            {page ? (
              <h1 id="song-title" className="mt-1 text-[26px] font-bold leading-tight tracking-tight sm:text-[34px]">
                {title}
              </h1>
            ) : (
              <h2 id="song-title" className="mt-1 text-[22px] font-bold leading-tight tracking-tight sm:text-[26px]">
                {title}
              </h2>
            )}
            {info?.t && info.t.length > 0 && (
              <div className="mt-1 space-y-0.5">
                {info.t.slice(0, 2).map(([l, name]) => (
                  <div key={l} className="truncate text-[12px] text-mist" title={`${LANG[l] ? t(LANG[l]) : l}: ${name}`}>
                    {name}
                  </div>
                ))}
              </div>
            )}
            <div className="mt-1.5 min-h-[1.25em] text-[14px] font-medium text-ink-2">{info?.a ?? ""}</div>
          </div>
        </div>
      </div>

      <div className={cx(page ? "mt-5" : "min-h-0 overflow-y-auto px-5 pb-5 sm:px-6 sm:pb-6")}>
        <dl className="grid grid-cols-2 gap-x-4 gap-y-2 rounded-[14px] border border-line bg-paper-2 px-4 py-3 text-[13px] sm:grid-cols-4">
          <Fact k={t("version")} v={info?.v ?? main.version} />
          <Fact k={t("length")} v={info ? mmss(info.d) : "–"} />
          <Fact k={t("jacket")} v={info?.jd ?? "–"} />
          <Fact k={t("source")} v={info?.s ?? "–"} />
        </dl>

        <h3 className="mb-2 mt-5 text-[13px] font-semibold text-mist">{t("charts")}</h3>
        <ul className="flex flex-col gap-2">
          {list.map((c) => {
            const r = analysis?.byId[c.id];
            const e = scores[c.id];
            const ci = info?.c[c.difficulty];
            const inBest = r && r.score !== null && r.rank <= 40 && r.effective > 0;
            const next = engine && !c.deleted && (e?.score ?? 0) < MAX_SCORE ? engine.minScore(c.id) : null;
            const hist = events.filter((h) => h.chartId === c.id);
            return (
              <li key={c.id} className={cx(diffClass(c.difficulty), "overflow-hidden rounded-[14px] border border-line bg-paper")}>
                <div className="flex items-stretch">
                  <div className="flex w-[72px] shrink-0 flex-col items-center justify-center gap-0.5 py-2.5 text-[#0b0910]" style={{ background: "var(--diff)" }}>
                    <span className="num text-[13px] font-bold leading-none">{c.difficulty}</span>
                    <span className="num text-[20px] font-bold leading-none">{c.constant.toFixed(1)}</span>
                  </div>
                  <div className="min-w-0 flex-1 px-3 py-2.5">
                    <div className="flex flex-wrap items-baseline gap-x-3 gap-y-0.5 text-[12px] text-mist">
                      <span>
                        {t("level")} <b className="num font-semibold text-ink">{c.level}</b>
                      </span>
                      {ci?.n && (
                        <span>
                          {t("notes")} <b className="num font-semibold text-ink">{ci.n[0].toLocaleString()}</b>
                        </span>
                      )}
                      {ci && <span className="min-w-0 truncate">{t("designer", { name: ci.cd })}</span>}
                      {c.deleted && <span className="text-warn">{t("deleted")}</span>}
                    </div>
                    <div className="mt-1.5 flex flex-wrap items-center gap-x-3 gap-y-1">
                      {e ? (
                        <>
                          <span className="num text-[16px] font-semibold">{fmtScore(e.score)}</span>
                          <LampBadge lamp={e.lamp} apPlus={e.score >= MAX_SCORE} />
                          {e.score < MAX_SCORE && <span className="text-[12px] text-mist">{grade(e.score)}</span>}
                          {r && (
                            <span className="num text-[13px] text-ink-2">
                              {r.excluded ? <span className="line-through">{r.rating.toFixed(4)}</span> : r.effective.toFixed(4)}
                            </span>
                          )}
                          {inBest && <span className="num rounded-full bg-accent-soft px-1.5 text-[11px] font-semibold text-accent">B{r.rank}</span>}
                        </>
                      ) : (
                        <span className="text-[13px] text-mist">{t("noRecord")}</span>
                      )}
                    </div>
                    {next !== null && (
                      <div className="mt-1 text-[12px] text-mist">
                        {rich(t("plusOne"), { score: <b className="num font-semibold text-accent">{fmtScore(next)}</b> })}
                        {e && <span className="num"> (+{(next - e.score).toLocaleString()})</span>}
                      </div>
                    )}
                    {hist.length > 0 && (
                      <ol className="mt-2 flex flex-col gap-0.5 border-l-2 pl-2.5 text-[12px]" style={{ borderColor: "color-mix(in oklab, var(--diff) 55%, transparent)" }} aria-label={t("history")}>
                        {hist.slice(0, 5).map((h, i) => (
                          <li key={`${h.at}-${i}`} className="num flex flex-wrap items-baseline gap-x-2 text-mist">
                            <span className="w-[58px] shrink-0">{day(h.at)}</span>
                            <span className="font-medium text-ink-2">{fmtScore(h.score)}</span>
                            {h.prevScore !== null && h.score > h.prevScore && <span className="text-good">+{(h.score - h.prevScore).toLocaleString()}</span>}
                            {h.prevScore === null && <span>{t("first")}</span>}
                            {h.lamp !== "none" && h.lamp !== h.prevLamp && <span className="font-semibold">{h.lamp.toUpperCase()}</span>}
                          </li>
                        ))}
                        {hist.length > 5 && <li className="text-mist">{t("more", { n: hist.length - 5 })}</li>}
                      </ol>
                    )}
                  </div>
                </div>
                {ci?.n && (
                  <div className="num flex flex-wrap gap-x-3 border-t border-line px-3 py-1.5 text-[11px] text-mist">
                    <span>Tap {ci.n[1]}</span>
                    <span>Flick {ci.n[2]}</span>
                    <span>Slide {ci.n[3]}</span>
                    <span>Catch {ci.n[4]}</span>
                    <span>Rotate {ci.n[5]}</span>
                  </div>
                )}
              </li>
            );
          })}
        </ul>

        <div className="mt-4 flex flex-wrap items-center justify-between gap-3 text-[12px] text-mist">
          <span>{t("credit")}</span>
          <div className="flex items-center gap-3">
            <button type="button" onClick={copyLink} className="font-semibold text-accent hover:underline">
              {t("copyLink")}
            </button>
            {!page &&
              (onOpenPage ? (
                <button type="button" onClick={onOpenPage} className="font-semibold text-accent hover:underline">
                  {t("songPage")}
                </button>
              ) : (
                <Link href={`/song/${encodeURIComponent(songId)}`} className="font-semibold text-accent hover:underline">
                  {t("songPage")}
                </Link>
              ))}
            {wikiUrl && (
              <a href={wikiUrl} target="_blank" rel="noreferrer" className="font-semibold text-accent hover:underline">
                {t("wiki")}
              </a>
            )}
          </div>
        </div>
      </div>
    </>
  );
}

function Fact({ k, v }: { k: string; v: string }) {
  return (
    <div className="min-w-0">
      <dt className="text-[11px] text-mist">{k}</dt>
      <dd className="num truncate font-medium text-ink" title={v}>
        {v}
      </dd>
    </div>
  );
}
